def glyph(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y1 = (7 - r) * PX            # top of this row; baseline is the bottom of the last row
        y0 = y1 - PX
        c = 0
        while c < 5:
            if row[c] == '#':
                s = c
                while c < 5 and row[c] == '#':
                    c += 1
                x0, x1 = s * PX + 100, c * PX + 100   # 1px left side bearing
                # 1-unit vertical overlap prevents hairline seams between rows at fractional scales.
                pen.moveTo((x0, y0 - 1))
                pen.lineTo((x0, y1 + 1))
                pen.lineTo((x1, y1 + 1))
                pen.lineTo((x1, y0 - 1))
                pen.closePath()
            else:
                c += 1
    return pen.glyph()


def main():
    names = {}
    order = ['.notdef']
    cmap = {}
    glyphs = {'.notdef': glyph(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'])}
    for ch, rows in G.items():
        name = 'space' if ch == ' ' else 'uni%04X' % ord(ch)
        order.append(name)
        glyphs[name] = glyph(rows)
        cmap[ord(ch)] = name
        if ch.isalpha():
            lo = ch.lower()
            lname = 'uni%04X' % ord(lo)
            order.append(lname)
            glyphs[lname] = glyph(rows)
            cmap[ord(lo)] = lname
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (ADV, 0) for n in order})
    fb.setupHorizontalHeader(ascent=ASC, descent=DESC)
    fb.setupNameTable({'familyName': 'Alrect Pixel', 'styleName': 'Regular', 'uniqueFontIdentifier': 'AlrectPixel-Regular', 'fullName': 'Alrect Pixel Regular', 'psName': 'AlrectPixel-Regular', 'version': 'Version 1.0', 'licenseDescription': 'Original work for the ALRECT FILE TOOLS project, released under the same MIT license as the project.'})
    fb.setupOS2(sTypoAscender=ASC, sTypoDescender=DESC, usWinAscent=ASC, usWinDescent=-DESC, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    out = os.path.join(os.path.dirname(__file__), '..', 'src', 'assets', 'fonts')
    os.makedirs(out, exist_ok=True)
    fb.font.flavor = 'woff'
    fb.font.save(os.path.join(out, 'alrect-pixel.woff'))
    print('wrote', len(order), 'glyphs ->', os.path.join(out, 'alrect-pixel.woff'))


if __name__ == '__main__':
    main()
