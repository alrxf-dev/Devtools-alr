// Generates docs/TOOL-STATUS.md from the registry so the list can never drift from the code.
import fs from 'node:fs';
import { TOOLS, CATEGORIES, countByStatus } from '../src/registry/index';

const c = countByStatus();
let out = `# Tool status\n\nGenerated by \`scripts/gen-status.ts\` from the registry. Do not edit by hand.\n\n`;
out += `Total: ${TOOLS.length} — working ${c.working}, partial ${c.partial}, backend ${c.backend}, unsupported ${c.unsupported}.\n\n`;
out += `"working" means the tool has at least one automated end-to-end case that runs it in headless Chromium (tests/e2e/cases). It does not mean it was tried on every browser or every possible file.\n\n`;
for (const cat of CATEGORIES) {
  out += `## ${cat.name}\n\n| Tool | Status | Note |\n|---|---|---|\n`;
  for (const t of TOOLS.filter((x) => x.category === cat.id)) out += `| ${t.name} (\`${t.id}\`) | ${t.status} | ${(t.statusNote ?? '').replace(/\|/g, '\\|')} |\n`;
  out += '\n';
}
fs.writeFileSync('docs/TOOL-STATUS.md', out);
console.log(`docs/TOOL-STATUS.md written (${TOOLS.length} tools)`);
